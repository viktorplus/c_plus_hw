/*
  ВІДПОВІДІ НА ЧАСТИНУ «ПОЯСНИ»

  1. static_cast робить лише «нормальні» перетворення, які компілятор може перевірити (int в double, нащадок у базовий і т.д.),
     і якщо перетворення безглузде — буде помилка компіляції. Крім того, його легко знайти в коді пошуком.
     (double)sum — перетворення в стилі C, яке пробує по черзі всі види cast-ів, включно з reinterpret_cast і const_cast.
     Тобто воно може мовчки перетворити покажчик на зовсім інший тип або зняти const, і компілятор не попередить —
     помилка вилізе вже під час роботи програми.

  2. sum і count — обидва int, тому 13 / 5 — це цілочисельне ділення, дробова частина відкидається, виходить 2,
     і вже потім ця 2 перетворюється в double 2.0. static_cast<double>(sum / count) робить те саме: спочатку
     ділить цілі числа (2), а вже потім перетворює результат. Треба перетворювати операнд ДО ділення:
     static_cast<double>(sum) / count — тоді count теж стає double і ділення дробове.

  3. Для покажчика dynamic_cast повертає nullptr, якщо об'єкт насправді не того типу, тому результат треба перевіряти.
     Для посилання nullptr повернути не можна (посилання не буває «порожнім»), тому він кидає виняток bad_cast.
     Якби в кроці 3 написати static_cast<Pawn*>, він би нічого не перевіряв і для коня, слона і тури теж повернув би
     «покажчик на пішака». Тоді виклик canPromote() читав би поле row, якого в коні немає, — це невизначена поведінка:
     могло б прочитатися сміття, і тура «перетворилася» б на ферзя, або програма впала б.

  4. dynamic_cast перевіряє тип під час роботи програми, а дізнатися справжній тип об'єкта можна лише через інформацію
     про тип, яка зберігається разом з таблицею віртуальних функцій. Якщо в класі немає жодного віртуального методу,
     такої таблиці немає, і компілятор видасть помилку. Перетворення пішака — виправданий випадок, бо вміння
     перетворюватися є ТІЛЬКИ в пішака: додавати canPromote у Piece як віртуальний метод для всіх фігур було б
     неправильно, бо кінь чи тура цього не вміють. Тому ми питаємо конкретний об'єкт «ти пішак?» і лише тоді
     працюємо з ним як з пішаком.
*/
