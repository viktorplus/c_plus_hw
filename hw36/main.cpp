// Хід пішака: якщо фігура не пішак, dynamic_cast кине bad_cast, і він піде в main
void pawnStep(Piece& piece)
{
    Pawn& pawn = dynamic_cast<Pawn&>(piece);
    pawn.advance();
}

// Виводить усі фігури і середню цінність
void showBoard(Piece** pieces, int count)
{
    for (int i = 0; i < count; i++)
    {
        cout << i + 1 << ". ";
        pieces[i]->print();
        cout << endl;
    }
    cout << "Середня цінність: " << getAverageValue(pieces, count) << endl;
}

