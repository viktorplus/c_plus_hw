// Інтерфейс магічного каменю
class IGem
{
public:
    virtual ~IGem() = default;
    virtual string getName() const = 0;
    virtual int getBonus() const = 0;          // додаткова шкода
    virtual string getEffect() const = 0;      // опис ефекту
};

class Ruby : public IGem
{
public:
    ~Ruby()
    {
        cout << "Рубін зруйновано" << endl;
    }

    string getName() const override
    {
        return "Рубін";
    }

    int getBonus() const override
    {
        return 10;
    }

    string getEffect() const override
    {
        return "вогонь";
    }
};

// ===== Ваш код =====

class Sapphire : public IGem
{
public:
    ~Sapphire()
    {
        cout << "Сапфір зруйновано" << endl;
    }

    string getName() const override
    {
        return "Сапфір";
    }

    int getBonus() const override
    {
        return 6;
    }

    string getEffect() const override
    {
        return "холод, ціль сповільнена";
    }
};

class Weapon
{
private:
    string name;
    int baseDamage;
    unique_ptr<IGem> socket;                    // камінь належить зброї; спочатку nullptr

public:
    Weapon(const string& name, int baseDamage) : name(name), baseDamage(baseDamage)
    {}

    // Вставляє камінь. Старий камінь (якщо був) знищується, коли socket отримує новий
    void insertGem(unique_ptr<IGem> gem)
    {
        if (!gem)
        {
            cout << name << ": немає каменю, нічого вставляти" << endl;
            return;
        }
        socket = move(gem);                     // тут старий камінь руйнується, а gem стає порожнім
        cout << name << ": вставлено " << socket->getName() << endl;
    }

    // Ювелір виймає камінь і віддає власність тому, хто викликав
    unique_ptr<IGem> removeGem()
    {
        if (!socket)
        {
            cout << name << ": сокет порожній" << endl;
            return nullptr;
        }
        cout << name << ": вийнято " << socket->getName() << endl;
        return move(socket);                    // після цього socket == nullptr
    }

    void attack() const
    {
        if (socket)
        {
            int bonus = socket->getBonus();
            cout << name << " б'є: " << baseDamage << " + " << bonus << " = " << baseDamage + bonus
                 << " шкоди (" << socket->getEffect() << ")" << endl;
        }
        else
        {
            cout << name << " б'є: " << baseDamage << " шкоди" << endl;
        }
    }
};

// Фабрика ювеліра: створює камінь потрібного типу
unique_ptr<IGem> createGem(const string& type)
{
    if (type == "sapphire")
    {
        return make_unique<Sapphire>();
    }
    return make_unique<Ruby>();
}

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // ---------------- КРОК 1 ----------------
    cout << "--- 1. Зброя без каменів ---" << endl;
    Weapon sword("Меч", 25);
    Weapon axe("Сокира", 40);
    sword.attack();

    // ---------------- КРОК 2 ----------------
    cout << endl << "--- 2. Рубін у меч ---" << endl;
    sword.insertGem(createGem("ruby"));
    sword.attack();

    // ---------------- КРОК 3 ----------------
    cout << endl << "--- 3. Сапфір поверх рубіна ---" << endl;
    sword.insertGem(createGem("sapphire"));     // рубін руйнується всередині insertGem, ще до повідомлення «вставлено»
    sword.attack();

    // ---------------- КРОК 4 ----------------
    cout << endl << "--- 4. Ювелір виймає сапфір ---" << endl;
    unique_ptr<IGem> gem = sword.removeGem();
    if (gem)
    {
        cout << "У сумці: " << gem->getName() << endl;
    }
    sword.attack();

    // ---------------- КРОК 5 ----------------
    cout << endl << "--- 5. Сапфір у сокиру ---" << endl;
    axe.insertGem(move(gem));
    axe.attack();
    if (gem == nullptr)
    {
        cout << "Покажчик gem тепер порожній — камінь належить сокирі" << endl;
    }

    // ---------------- КРОК 6 ----------------
    cout << endl << "--- 6. Сапфір падає в лаву ---" << endl;
    axe.removeGem();                            // результат ніхто не забрав — тимчасовий unique_ptr знищує сапфір
    cout << "(після рядка axe.removeGem();)" << endl;
    axe.removeGem();

    // ---------------- КРОК 7 ----------------
    cout << endl << "--- 7. Кинджал з рубіном ---" << endl;
    {
        Weapon dagger("Кинджал", 12);
        dagger.insertGem(createGem("ruby"));
        dagger.attack();
    }                                           // тут dagger знищується, а разом з ним і рубін
    cout << "Кинджал продано торговцю" << endl;

    cout << endl << "--- Кінець main ---" << endl;
    return 0;
}

/*
  ВІДПОВІДІ НА ЧАСТИНУ «ПОЯСНИ»

  1. unique_ptr — єдиний власник об'єкта, тому конструктор копіювання і operator= копіюванням у нього видалені (= delete).
     Якби копіювати було можна, два покажчики видалили б той самий камінь двічі. Після removeGem() у полі socket меча
     лежить nullptr — власність перейшла до того, хто викликав. Усередині insertGem параметр gem — це іменована змінна (lvalue),
     і без move компілятор спробує її скопіювати, а копіювати не можна. А createGem("ruby") повертає тимчасовий об'єкт (rvalue),
     його і так можна перемістити, тому move там не потрібен.

  2. Рубін руйнує сам unique_ptr socket у рядку socket = move(gem): перед тим як забрати новий камінь, він видаляє старий.
     Тому «Рубін зруйновано» виводиться ще до «Меч: вставлено Сапфір». Деструктор з delete у Weapon не потрібен, бо
     деструктор поля socket сам викличе delete для каменю, коли знищиться зброя. На кроці 6 removeGem повернув unique_ptr,
     який ніхто не зберіг, — тимчасовий об'єкт знищився в кінці рядка і забрав із собою сапфір. На кроці 7 кинджал вийшов
     за межі блоку { }, його деструктор знищив поле socket, а з ним і рубін — тому «Рубін зруйновано» з'являється
     перед «Кинджал продано торговцю».

  3. Камінь видаляється через покажчик на базовий клас IGem. Якщо деструктор у IGem не віртуальний, delete викличе тільки
     ~IGem(), а деструктор Ruby чи Sapphire не викличеться — це невизначена поведінка: ресурси нащадка не звільняться,
     і повідомлення «Рубін зруйновано» ми б не побачили. Віртуальний деструктор гарантує, що спочатку викличеться
     деструктор справжнього класу об'єкта.

  4. unique_ptr — один власник, копіювати не можна, тільки переміщати; накладних витрат майже немає, як у звичайного покажчика.
     shared_ptr — спільне володіння: кілька покажчиків на один об'єкт і лічильник посилань, об'єкт видаляється, коли зникає
     останній shared_ptr. weak_ptr — «спостерігач» за shared_ptr: не збільшує лічильник, не тримає об'єкт живим, потрібен,
     щоб розірвати циклічні посилання. За замовчуванням беруть unique_ptr, бо він найпростіший і найдешевший, і чітко показує,
     хто власник; shared_ptr — лише коли власників справді кілька.

*/
