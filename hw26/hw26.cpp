class Gradebook
{
private:
    int* grades;
    int count;

public:
    explicit Gradebook(int count) : grades(nullptr), count(count)
    {
        if (this->count < 1)
        {
            this->count = 1;
        }
        grades = new int[this->count];
        for (int i = 0; i < this->count; i++)
        {
            grades[i] = 0;
        }
    }
    Gradebook(double count) = delete;
    // 5. Що сталося б при Gradebook copy = book;, якби копіювання не було заборонене?
    // 
	// Як що копіювання не було заборонене, то при Gradebook copy = book; створювався б новий об'єкт copy, 
    // який мав би власний динамічний масив grades. Це могло б призвести до проблем з управлінням пам'яттю,
    // таких як подвійне видалення одного й того ж масиву при виклику деструктора для обох об'єктів (оригіналу і копії),
    // що може спричинити помилки виконання або витоки пам'яті. Тому копіювання заборонене, щоб уникнути таких проблем.

    Gradebook(const Gradebook& other) = delete;
    Gradebook& operator=(const Gradebook& other) = delete;

    ~Gradebook()
    {
        delete[] grades;
    }

    //  2. Навіщо дві версії []? Яка з них викликається в bestGrade і чому?
    // 
    // Дві версії [] потрібні для забезпечення доступу до елементів як для константних, так і для неконстантних об'єктів.
    // Неконстантна версія повертає посилання, що дозволяє змінювати оцінки, а константна версія повертає значення, що дозволяє лише читати оцінки.
    // У bestGrade викликається константна версія, оскільки bestGrade працює з константним об'єктом Gradebook.
    // 
    //  3. (Рівень 2) Чому через[] не можна перевірити, що оцінка в межах 1..12, а через setGrade — можна ?
    // 
	// Через [] немає механізму для перевірки діапазону значень, оскільки він просто повертає посилання на елемент масиву.

    int& operator[](int lesson)
    {
        return grades[lesson];
    }

    //  2. Навіщо дві версії []? Яка з них викликається в bestGrade і чому?
    // 
    //  через константну версію [] bestGrade працює з константним об'єктом Gradebook
    //  Неконстантна версія повертає посилання, що дозволяє змінювати оцінки
    // 
    int operator[](int lesson) const
    {
        return grades[lesson];
    }

    int getCount() const
    {
        return count;
    }

    double average() const
    {
        int sum = 0;
        int graded = 0;
        for (int i = 0; i < count; i++)
        {
            if (grades[i] > 0)
            {
                sum += grades[i];
                graded++;
            }
        }
        if (graded == 0)
        {
            return 0;
        }
        return (double)sum / graded;
    }

    //  3. (Рівень 2) Чому через[] не можна перевірити, що оцінка в межах 1..12, а через setGrade — можна ?
	//  тому що через [] немає механізму для перевірки діапазону значень, оскільки він просто повертає посилання
    //  на елемент масиву а через setGrade можна перевірити, що оцінка в межах 1..12, бо там є логіка перевірки перед присвоєнням значення.

    bool setGrade(int lesson, int grade)
    {
        if (lesson < 0 || lesson >= count || grade < 1 || grade > 12)
        {
            return false;
        }
        grades[lesson] = grade;
        return true;
    }

    //   4. Навіщо explicit в operator bool? Який рядок скомпілювався б без нього?
    //
    // explicit запобігає неявному перетворенню об'єкта Gradebook
    // у bool та далі в інші типи, наприклад int.
    //
    // Без explicit скомпілювався б рядок:
    // int n = olena;

    explicit operator bool() const
    {
        for (int i = 0; i < count; i++)
        {
            if (grades[i] > 0)
            {
                return true;
            }
        }
        return false;
    }


    friend ostream& operator<<(ostream& out, const Gradebook& book);
    friend istream& operator>>(istream& in, Gradebook& book);
};

//  1. Чому operator<< для Gradebook — дружня функція, а не метод класу?
// тому що operator<< приймає об'єкт ostream як перший параметр, а не Gradebook. Це дозволяє використовувати синтаксис потоку виводу (cout << book) 
// і забезпечує узгодженість з іншими типами даних, які також використовують operator<< для виводу.

ostream& operator<<(ostream& out, const Gradebook& book)
{
    out << "Оцінки:";
    for (int i = 0; i < book.count; i++)
    {
        if (book.grades[i] > 0)
        {
            out << " " << book.grades[i];
        }
        else
        {
            out << " -";
        }
    }
    out << " | середній бал: " << book.average();
    return out;
}

istream& operator>>(istream& in, Gradebook& book)
{
    for (int i = 0; i < book.count; i++)
    {
        in >> book.grades[i];
        if (book.grades[i] < 0 || book.grades[i] > 12)
        {
            book.grades[i] = 0;
        }
    }
    return in;
}

//  2. Навіщо дві версії []? Яка з них викликається в bestGrade і чому?
// через константну версію [] bestGrade працює з константним об'єктом Gradebook
// Неконстантна версія повертає посилання, що дозволяє змінювати оцінки

int bestGrade(const Gradebook& book)
{
    int best = 0;
    for (int i = 0; i < book.getCount(); i++)
    {
        if (book[i] > best)
        {
            best = book[i];
        }
    }
    return best;
}

//  6. (Рівень 3) Яким ви зробили operator< — методом, дружньою чи глобальною функцією? Чому?
// Я зробив operator< глобальною функцією, оскільки порівняння двох об'єктів Gradebook не потребує доступу до приватних членів класу.
bool operator<(const Gradebook& first, const Gradebook& second)
{
    return first.average() < second.average();
}

