/*
  ВІДПОВІДІ НА ЧАСТИНУ «ПОЯСНИ»

  1. Виняток — це об'єкт, який кидають через throw, коли функція не може виконати свою роботу, і програма
     переходить до найближчого catch, що підходить. loadCargo кидає виняток, бо false легко проігнорувати:
     хтось викличе метод, не перевірить результат, і програма піде далі, ніби все нормально. Виняток
     проігнорувати не вийде — або його обробиш, або програма завершиться. До того ж виняток несе текст помилки.
     Конструктор взагалі нічого не повертає, тому без винятків довелося б робити якийсь прапорець типу isValid
     і перевіряти його після створення, або окремий метод init, який повертає bool. А з винятком «поганий» об'єкт просто не створюється.

  2. У try пишемо код, який може кинути виняток. throw створює об'єкт винятку і зупиняє виконання поточної функції,
     далі шукається catch з відповідним типом — перший, що підходить, і виконується. Після catch програма йде
     далі після всього блоку try/catch. У кроці 2 встигли завантажитися Продукти і Вода, на Руді кинуто
     runtime_error, а launch уже не виконався. Назад у try програма не повертається, бо throw — це не виклик функції,
     а вихід з блоку: код після місця помилки міг залежати від того, що не вдалося, тому його просто пропускають.

  3. За посиланням — щоб не копіювати об'єкт винятку і не «обрізати» його до базового класу (якщо ловити exception
     за значенням, залишиться тільки частина exception). const — бо змінювати виняток ми не збираємось.
     invalid_argument і runtime_error — нащадки класу exception, а посилання на базовий клас може дивитися на нащадка,
     тому catch (const exception&) ловить обидва. what() віртуальний, тому виводиться саме наш текст.

  4. Розкрутка стека — це коли виняток вилітає з функції, і по дорозі до catch знищуються всі локальні об'єкти
     функцій, з яких він виходить (викликаються їхні деструктори). Airlock — локальний об'єкт у loadManifest,
     тому коли loadCargo кинула виняток, вихід з loadManifest знищив airlock і його деструктор закрив шлюз.
     Тому «[шлюз закрито]» видно ще ДО повідомлення центру управління — catch виконується вже після розкрутки.
*/
